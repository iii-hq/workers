/**
 * What the plugin's SessionStart hook adds to a new session: the default
 * profile, `default-mcp`, read from mcp-server. mcp-server's instructions ask
 * the agent to load it, but Claude Code defers MCP tools until they are
 * searched for, so a session that starts on a small question never does. A
 * hook's `additionalContext` puts the profile in every session for sure.
 */

import type { AgentProfile } from './directory.js';

export const DEFAULT_PROFILE = 'default-mcp';
/** Claude Code keeps hook output under 10,000 characters in context. */
export const MAX_CONTEXT = 9_500;

function output(additionalContext: string): string {
  return JSON.stringify({
    hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext },
  });
}

/**
 * The first line inside the generated agent's frontmatter, as a YAML comment:
 * Claude Code reads frontmatter only when `---` opens the file, and a comment
 * there never reaches the agent's instructions.
 */
export const GENERATED_NOTE =
  '# Generated by the iii plugin from the default-mcp agent profile (iii-directory/prompts/default-mcp.md); changes here are overwritten.';

/** The line asking the agent to read a profile's skills, or '' when it has none. */
function preloadLine(skills: string[]): string {
  return skills.length
    ? `Before your first task, read each of its skills with \`iii_get_skill\`: ${skills.map((s) => `\`${s}\``).join(', ')}.`
    : '';
}

/**
 * A profile as instructions: its prompt, then the line asking for its skills.
 * The SessionStart hook adds the same line; worker installs have no such
 * hook, so the appended text and the agent carry it themselves.
 */
export function profileText(profile: AgentProfile): string {
  const prompt = (profile.system_prompt ?? '').trim();
  const preload = preloadLine(profile.skills ?? []);
  return preload ? `${prompt}\n\n${preload}` : prompt;
}

/**
 * The plugin's `iii` agent (`agents/iii.md`, run with `--agent iii:iii`),
 * built from the `default-mcp` profile: its body is the profile's prompt, so
 * there is no second, hand-written copy of the rules to drift.
 */
export function agentFile(profile: AgentProfile): string {
  const description =
    'The iii agent: the engine default-mcp profile, from iii-directory through mcp-server. Works through the iii tools.';
  return `---\n${GENERATED_NOTE}\nname: iii\ndescription: ${JSON.stringify(description)}\n---\n\n${profileText(profile)}\n`;
}

/** The hook's stdout, for the profile mcp-server returned or the error it hit. */
export function sessionStartOutput(result: { profile: AgentProfile } | { error: string }): string {
  if ('error' in result) {
    return output(
      `The iii plugin could not load the \`${DEFAULT_PROFILE}\` agent profile at session start: ${result.error}`,
    );
  }
  const { profile } = result;
  const id = profile.id || DEFAULT_PROFILE;
  const skills = profile.skills ?? [];
  const header = `Your iii agent profile is \`${id}\`, loaded by the iii plugin at session start from the engine's mcp-server. Follow it for this session, until /iii:profile or /iii:<profile> loads another.`;
  const preload = skills.length ? `\n\n${preloadLine(skills)}` : '';
  const body = `${header}${preload}\n\n<profile id="${id}">\n${profile.system_prompt ?? ''}\n</profile>`;
  if (body.length < MAX_CONTEXT) return output(body);
  return output(
    // Bounded whatever the profile holds: no prompt, no skill list.
    `${header} It is too long to include here: load it now with \`iii_get_agent\` (\`activate: true\`, id \`${id}\`), follow its \`system_prompt\`, and read each id in its \`skills\` with \`iii_get_skill\`.`,
  );
}
