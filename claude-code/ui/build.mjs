#!/usr/bin/env node

/**
 * Build this worker's two console assets and embed them in the worker.
 *
 *   ui/page.tsx    → ui/dist/page.js     (injected over `console:script`)
 *   ui/styles.css  → ui/dist/styles.css  (injected over `console:style`)
 *   both           → src/ui-assets.generated.ts
 *
 * The generated module is why the embed step exists: `deploy: bundle` ships
 * ONE file, so a worker that read `ui/dist` at runtime would serve nothing
 * once published. Rust workers solve this with `include_str!`; a Node worker
 * generates a module and imports it.
 *
 * The five shared specifiers stay EXTERNAL — they resolve at runtime through
 * the console's import map (a bundled React copy surfaces as a cryptic
 * "Invalid hook call"). Everything else the page needs is bundled in.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ui = join(root, 'ui');
const dist = join(ui, 'dist');
const watch = process.argv.includes('--watch');

const options = {
  entryPoints: [join(ui, 'page.tsx'), join(ui, 'styles.css')],
  bundle: true,
  format: 'esm',
  jsx: 'automatic',
  outdir: dist,
  // The console rejects an asset over 8 MiB and the bundle carries these as
  // string literals; readable stack traces only matter under --watch.
  minify: !watch,
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', '@iii-dev/console-ui'],
  logLevel: 'info',
};

async function embed() {
  const [page, styles] = await Promise.all([
    readFile(join(dist, 'page.js'), 'utf8'),
    readFile(join(dist, 'styles.css'), 'utf8'),
  ]);
  const generated = `// Generated by scripts/build-ui.mjs — do not edit.
/* biome-ignore-all lint: generated file */
export const PAGE_JS = ${JSON.stringify(page)};
export const STYLES_CSS = ${JSON.stringify(styles)};
`;
  await mkdir(join(root, 'src'), { recursive: true });
  await writeFile(join(root, 'src/ui-assets.generated.ts'), generated);
}

if (watch) {
  const ctx = await esbuild.context({
    ...options,
    plugins: [
      {
        name: 'embed-after-build',
        setup(build) {
          build.onEnd(async (result) => {
            if (result.errors.length === 0) await embed();
          });
        },
      },
    ],
  });
  await ctx.watch();
} else {
  await esbuild.build(options);
  await embed();
}
