import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const require = createRequire(new URL('../../../ade/web/package.json', import.meta.url))
const { createServer } = await import(require.resolve('vite'))
const { chromium, expect } = require('@playwright/test')
const server = await createServer({ configFile: fileURLToPath(new URL('./vite.config.mjs', import.meta.url)) })
await server.listen()
const evidence = fileURLToPath(new URL('../../docs/evidence/group-investigation-a73c', import.meta.url))
const observations = []
let browser
const issue1 = 'TimeoutError: upstream request exceeded deadline'
const issue2 = 'ConnectionError: socket closed during response'
const issue3 = 'TypeError: optional metadata missing'
const attempts = page => page.evaluate(() => window.__SENTINEL_FIXTURE__.calls.filter(call => call.id === 'sentinel::investigate_many'))
const setMode = (page, mode) => page.evaluate(mode => { window.__SENTINEL_FIXTURE__.mode = mode }, mode)
const selected = page => page.getByText('2 selected', { exact: true })
const review = page => page.getByRole('dialog', { name: 'Investigate in group', exact: true })
const start = page => review(page).getByRole('button', { name: 'Start investigation', exact: true })
const openReview = async page => {
  const button = page.getByRole('button', { name: 'Investigate in group', exact: true })
  await button.focus()
  await page.keyboard.press('Enter')
  await expect(review(page)).toBeVisible()
}
const chooseProfile = async (page, mobile) => {
  const picker = review(page).getByRole('combobox', { name: 'Investigation profile', exact: true })
  await expect(picker).toBeEnabled()
  await picker.click()
  const broken = page.getByRole('option', { name: /Broken chain · broken-fixture/ })
  await expect(broken).toBeDisabled()
  const option = page.getByRole('option', { name: /Default · default/ })
  await option.click()
  await expect(start(page)).toBeEnabled()
}
const capture = async (page, name) => {
  const text = await page.locator('body').innerText()
  assert.equal(/-----BEGIN .*PRIVATE KEY-----|AKIA[A-Z0-9]{16}|gh[pousr]_[A-Za-z0-9]{30,}/.test(text), false, 'Sensitive content before screenshot')
  await page.screenshot({ path: `${evidence}/sr-regression-${name}.png`, fullPage: true })
}
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH })
  for (const theme of ['dark', 'light']) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
    page.setDefaultTimeout(6000)
    const errors = []
    const network = []
    page.on('pageerror', error => errors.push(String(error)))
    page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:4197/') && !request.url().startsWith('data:')) network.push(request.url()) })
    await page.goto(`http://127.0.0.1:4197/?theme=${theme}`)
    await page.getByRole('checkbox', { name: `Select ${issue1}`, exact: true }).check()
    await expect(page.getByRole('button', { name: 'Investigate in group', exact: true })).toBeDisabled()
    await page.getByRole('checkbox', { name: `Select ${issue2}`, exact: true }).check()
    await capture(page, `wide-${theme}`)
    await openReview(page)
    await chooseProfile(page, false)
    await expect(review(page).getByText(/3500 UTF-8 bytes per issue/)).toBeVisible()
    await expect(review(page).getByText(/32768 bytes/)).toBeVisible()
    await capture(page, `review-wide-${theme}`)
    await review(page).getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal((await attempts(page)).length, 0)
    await expect(selected(page)).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('[aria-label="Error groups"]').waitFor()
    await expect(selected(page)).toBeVisible()
    await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(2)
    await capture(page, `phone-${theme}`)
    await setMode(page, 'catalog-error')
    await openReview(page)
    await expect(review(page).getByText('Could not load installed profiles', { exact: true })).toBeVisible()
    await expect(start(page)).toBeDisabled()
    await expect(review(page).getByRole('combobox', { name: 'Investigation profile', exact: true })).toBeDisabled()
    await capture(page, `catalog-error-${theme}`)
    await setMode(page, 'success')
    await review(page).getByRole('button', { name: 'Retry profiles', exact: true }).click()
    await chooseProfile(page, true)
    const hypothesis = review(page).getByRole('textbox', { name: 'Shared-cause hypothesis (optional)', exact: true })
    await hypothesis.fill('é'.repeat(1000))
    await expect(start(page)).toBeEnabled()
    await hypothesis.fill('é'.repeat(1001))
    await expect(start(page)).toBeDisabled()
    await expect(review(page).getByText('2002 / 2000 UTF-8 bytes. This is a hypothesis, not a conclusion.', { exact: true })).toBeVisible()
    await hypothesis.fill('Compare without assuming one cause')
    await capture(page, `review-phone-${theme}`)
    await setMode(page, 'overlap')
    await start(page).focus()
    await page.keyboard.press('Enter')
    await expect(review(page).getByRole('alert')).toContainText('Investigation overlap: no partial session was started.')
    assert.equal((await attempts(page)).length, 1)
    await capture(page, `overlap-${theme}`)
    await setMode(page, 'transport-error')
    await start(page).click()
    await expect(review(page).getByRole('alert')).toContainText('Fixture transport unavailable')
    assert.equal((await attempts(page)).length, 2)
    await expect(hypothesis).toHaveValue('Compare without assuming one cause')
    await expect(page.getByText('2 selected', { exact: true })).toBeVisible()
    await capture(page, `transport-error-${theme}`)
    // A changed intent gets a fresh request ID even when an earlier request failed.
    await hypothesis.fill('Compare independently after checking the evidence')
    await start(page).click()
    await expect(review(page).getByRole('alert')).toContainText('Fixture transport unavailable')
    const failed = await attempts(page)
    assert.equal(failed.length, 3)
    assert.equal(failed[0].payload.request_id, failed[1].payload.request_id)
    assert.notEqual(failed[1].payload.request_id, failed[2].payload.request_id)
    await page.evaluate(() => { window.__SENTINEL_FIXTURE__.mode = 'success'; window.__SENTINEL_FIXTURE__.delay = 800 })
    await start(page).evaluate(button => { button.click(); button.click() })
    const pending = review(page).getByRole('button', { name: 'Starting investigation…', exact: true })
    await expect(pending).toBeDisabled()
    await expect(hypothesis).toBeDisabled()
    await expect(review(page).getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(review(page)).toBeVisible()
    await capture(page, `pending-${theme}`)
    await expect(review(page)).toBeHidden()
    const requests = await attempts(page)
    assert.equal(requests.length, 4, 'One synchronous double activation must send one request')
    assert.equal(requests[2].payload.request_id, requests[3].payload.request_id)
    assert.deepEqual(requests[3].payload.group_ids, ['fixture-issue-1', 'fixture-issue-2'])
    assert.equal(requests[3].payload.profile_id, 'default')
    await expect(page.getByRole('region', { name: 'Selected groups', exact: true })).toHaveCount(0)
    await capture(page, `success-phone-${theme}`)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    // Keyboard selection and Escape preserve the selection without sending.
    const firstPick = page.getByRole('checkbox', { name: `Select ${issue1}`, exact: true })
    await firstPick.focus()
    await page.keyboard.press('Space')
    await page.getByRole('checkbox', { name: `Select ${issue2}`, exact: true }).check()
    await openReview(page)
    await page.keyboard.press('Escape')
    await expect(review(page)).toBeHidden()
    await expect(selected(page)).toBeVisible()
    assert.equal((await attempts(page)).length, 4)
    // Empty catalog disables start; close/cancel preserve the two picks.
    await setMode(page, 'catalog-empty')
    await openReview(page)
    await expect(review(page).getByText('No installed profiles available', { exact: true })).toBeVisible()
    await expect(start(page)).toBeDisabled()
    await review(page).getByRole('button', { name: 'Cancel', exact: true }).click()
    await setMode(page, 'success')
    // Optional hypothesis stays absent from the wire payload, not an empty string.
    await openReview(page)
    await chooseProfile(page, true)
    await start(page).click()
    await expect(review(page)).toBeHidden()
    const optional = await attempts(page)
    assert.equal(optional.length, 5)
    assert.equal('hypothesis' in optional[4].payload, false)
    // Six selected is visible but cannot start; five is accepted by the dialog.
    for (const checkbox of await page.getByRole('checkbox').all()) await checkbox.check()
    await expect(page.getByText('6 selected', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Investigate in group', exact: true })).toBeDisabled()
    await page.getByRole('checkbox', { name: 'Select NetworkError: name lookup failed', exact: true }).uncheck()
    await openReview(page)
    await expect(review(page).locator('li')).toHaveCount(5)
    await review(page).getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Clear', exact: true }).click()
    await page.getByRole('button', { name: `Open ${issue1}`, exact: true }).click()
    assert.equal(await page.evaluate(() => window.__SENTINEL_FIXTURE__.calls.some(call => Array.isArray(call) && call[0] === 'open')), true)
    assert.deepEqual(errors, [])
    assert.deepEqual(network, [])
    observations.push({ theme, viewports: ['1440x1000', '390x844'], checks: ['min/max selection', 'local combobox/option desktop and mobile', 'broken inheritance disabled', 'catalog failure/retry/empty', 'cancel and Escape no start', 'wide-to-phone preserves picks', 'keyboard Enter/Space/Escape', 'UTF8 2000-byte boundary', '3500 evidence excerpt and 32768 context budget', 'explicit overlap', 'transport retry same request ID', 'changed intent fresh request ID', 'pending double activation one RPC', 'pending Escape retains dialog', 'success clears selection', 'optional hypothesis omitted', 'individual row open preserved', 'no horizontal overflow', 'no external requests', 'no pageerrors'], requests: optional, errors })
    await page.close()
    // Narrow desktop split: pane width, not viewport, determines list layout.
    const split = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
    split.setDefaultTimeout(6000)
    await split.goto(`http://127.0.0.1:4197/?theme=${theme}&pane=600`)
    await split.locator('[aria-label="Error groups"]').waitFor()
    await split.getByRole('checkbox', { name: `Select ${issue1}`, exact: true }).check()
    await split.getByRole('checkbox', { name: `Select ${issue3}`, exact: true }).check()
    await openReview(split)
    await chooseProfile(split, false)
    await capture(split, `review-pane600-${theme}`)
    await split.keyboard.press('Escape')
    await expect(review(split)).toBeHidden()
    await expect(selected(split)).toBeVisible()
    assert.equal((await attempts(split)).length, 0)
    assert.equal(await split.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    observations.push({ theme, pane: '600px in 1440x1000 viewport', checks: ['narrow pane keyboard', 'desktop Select semantics in narrow pane', 'cancel preserves selection', 'no RPC start', 'no overflow'] })
    await split.close()
  }
  await writeFile(`${evidence}/sr-regression.json`, JSON.stringify({ baseline: '9eb9b507598a0dbe0937b883aebe89ebcba7f6bb', conditions: { reducedMotion: true, source: 'real GroupsListView + InvestigateMany + Console primitives; only iii RPC host mocked', pixelReview: 'not performed by this script' }, observations }, null, 2))
  console.log(JSON.stringify({ ok: true, observations }))
} catch (error) {
  await writeFile(`${evidence}/sr-regression-failure.json`, JSON.stringify({ error: String(error), stack: error.stack, observations }, null, 2))
  throw error
} finally { await browser?.close(); await server.close() }
