/**
 * Generate the `/vendor/*` shared-dependency shims for injectable UI.
 *
 * Each shim re-exports the console's own bundled React (exposed on
 * `window.__III_CONSOLE__` by main.tsx) under the bare specifier the
 * import map binds. ESM named exports must be enumerated statically, and
 * hand-pinning the list is a hazard: one omitted export inside anything a
 * worker bundled is a whole-script SyntaxError at import() time. So the
 * export lists are generated here from the INSTALLED packages' production
 * export sets — never hand-maintained. Runs as `prebuild`/`predev`
 * (package.json); output is checked in under public/vendor/ so the Vite
 * build copies it into dist/ and rust-embed ships it.
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import componentNames from '@iii-dev/console-ui/component-names'

const outDir = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'public',
  'vendor',
)

const SHIMS = [
  { file: 'react.js', global: 'React', specifier: 'react' },
  { file: 'react-dom.js', global: 'ReactDOM', specifier: 'react-dom' },
  {
    file: 'react-dom-client.js',
    global: 'ReactDOMClient',
    specifier: 'react-dom/client',
  },
  {
    file: 'jsx-runtime.js',
    global: 'JsxRuntime',
    specifier: 'react/jsx-runtime',
  },
]

const HEADER = (specifier) =>
  `// GENERATED by scripts/generate-vendor-shims.mjs — do not edit.\n` +
  `// Re-exports the console's bundled '${specifier}' from window.__III_CONSOLE__\n` +
  `// (boot contract: iii/tech-specs/2026-07-17-injectable-ui/slots-and-api.md).\n`

await mkdir(outDir, { recursive: true })

// Node's CJS-ESM interop can synthesize namespace keys that are not valid
// identifiers (react ships a literal `module.exports` key) — emitting one
// into the destructuring list is a whole-shim SyntaxError at import() time.
const VALID_IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const RESERVED = new Set([
  'default',
  'class',
  'function',
  'var',
  'let',
  'const',
  'new',
  'delete',
  'typeof',
  'instanceof',
  'void',
  'in',
  'of',
  'this',
  'super',
  'import',
  'export',
  'extends',
  'enum',
  'null',
  'true',
  'false',
  'if',
  'else',
  'for',
  'while',
  'do',
  'switch',
  'case',
  'return',
  'throw',
  'try',
  'catch',
  'finally',
  'break',
  'continue',
  'with',
  'yield',
  'await',
  'static',
  'implements',
  'interface',
  'package',
  'private',
  'protected',
  'public',
])

/** Parse + evaluate the shim in Node with a stubbed window — a bad export
 *  name or reference must fail the BUILD, never a browser tab. */
async function validateShim(file, content) {
  globalThis.window ??= {
    __III_CONSOLE__: {
      React: {},
      ReactDOM: {},
      ReactDOMClient: {},
      JsxRuntime: {},
      api: { iii: {}, components: {}, useTheme() {}, tokens: [] },
    },
  }
  const url = `data:text/javascript;base64,${Buffer.from(content).toString('base64')}`
  try {
    await import(url)
  } catch (err) {
    throw new Error(`generated vendor/${file} does not evaluate: ${err}`)
  }
}

for (const shim of SHIMS) {
  const mod = await import(shim.specifier)
  const names = Object.keys(mod)
    .filter(
      (k) => VALID_IDENT.test(k) && !RESERVED.has(k) && !k.startsWith('__'),
    )
    .sort()
  if (names.length === 0) {
    throw new Error(`no named exports found for ${shim.specifier}`)
  }
  const content =
    HEADER(shim.specifier) +
    `const M = window.__III_CONSOLE__.${shim.global}\n` +
    `export default M.default ?? M\n` +
    `export const {\n  ${names.join(',\n  ')},\n} = M\n`
  await validateShim(shim.file, content)
  await writeFile(join(outDir, shim.file), content)
  console.log(`vendor/${shim.file}: ${names.length} named exports`)
}

// The @iii-dev/console-ui shim re-exports the api object main.tsx builds
// once the engine client resolves (always before any injected module can
// evaluate — the loader is the only importer). The component list comes
// from the workspace package's manifest — the same list the conformance
// test holds the curated record to — so the shim's named exports can never
// drift from what the package's types declare.
for (const name of componentNames) {
  if (!VALID_IDENT.test(name) || RESERVED.has(name)) {
    throw new Error(`invalid component export name: ${name}`)
  }
}
const consoleUi =
  `// GENERATED by scripts/generate-vendor-shims.mjs — do not edit.\n` +
  `// The '@iii-dev/console-ui' module surface, from window.__III_CONSOLE__.api.\n` +
  `const api = window.__III_CONSOLE__.api\n` +
  `if (!api) throw new Error('@iii-dev/console-ui imported before the console api was ready')\n` +
  `export const iii = api.iii\n` +
  `export const components = api.components\n` +
  `export const useTheme = api.useTheme\n` +
  `export const tokens = api.tokens\n` +
  `export const {\n  ${componentNames.join(',\n  ')},\n} = api.components\n` +
  `export default api\n`
await validateShim('console-ui.js', consoleUi)
await writeFile(join(outDir, 'console-ui.js'), consoleUi)
console.log(
  `vendor/console-ui.js: api shim + ${componentNames.length} components`,
)
