/*
 * Titles. A history's first prompt is rarely the person's own words: hosts
 * and agents wrap it in context blocks (Conductor's `<system_instruction>`,
 * Codex's `<environment_context>` and AGENTS.md, Claude Code's reminders and
 * slash-command echoes). The worker titles a history from what is left once
 * those are gone (`ade/src/conversations/source.rs`, `prompt_text` and
 * `title_from_prompt`); these mirror it so the preview can show a prompt the
 * same way, and so a title from an older worker still reads as one.
 */

const INJECTED_TAGS = new Set([
  'system_instruction',
  'system-instruction',
  'system-reminder',
  'system_reminder',
  'environment_context',
  'user_instructions',
  'developer_instructions',
  'instructions',
  'command-name',
  'command-message',
  'command-args',
  'command-contents',
  'local-command-stdout',
  'local-command-stderr',
  'local-command-caveat',
  'user-prompt-submit-hook',
  'ide_selection',
  'ide_opened_file',
  'ide_diagnostics',
  'turn_aborted',
  'user_shell_command',
  'bash-input',
  'bash-stdout',
  'bash-stderr',
  'task-notification',
])

const INJECTED_LINES = [
  'caveat: the messages below were generated by the user',
  '# agents.md instructions for',
  '[request interrupted by user',
  'the user has attached these files',
]

const OPEN_TAG = /^<([A-Za-z][\w:-]*)(?=[\s>])[^>\n]*>/

/**
 * The person's own words in a recorded prompt: injected wrapper blocks (and a
 * leading block of any tag), agent boilerplate lines and attachment paths
 * removed. Empty when the turn was all context.
 */
export function promptText(text: string): string {
  let kept = ''
  let rest = text
  let leading = true
  for (let start = rest.indexOf('<'); start >= 0; start = rest.indexOf('<')) {
    const before = rest.slice(0, start)
    const tail = rest.slice(start)
    kept += before
    if (before.trim()) leading = false
    const open = OPEN_TAG.exec(tail)
    if (open) {
      const name = open[1].toLowerCase()
      const injected = INJECTED_TAGS.has(name)
      if (leading || injected) {
        const inner = tail.slice(open[0].length)
        const close = `</${name}>`
        const at = inner.toLowerCase().indexOf(close)
        if (at >= 0) {
          rest = inner.slice(at + close.length)
          continue
        }
        // A known wrapper cut short (a clipped record) runs to the end.
        if (injected) {
          rest = ''
          break
        }
      }
    }
    kept += '<'
    rest = tail.slice(1)
    leading = false
  }
  kept += rest
  return kept
    .split('\n')
    .filter((line) => {
      const lower = line.trim().toLowerCase()
      return !INJECTED_LINES.some((prefix) => lower.startsWith(prefix))
    })
    .map((line) =>
      line
        .split(' ')
        .filter((word) => !word.includes('.context/attachments/'))
        .join(' '),
    )
    .join('\n')
    .trim()
}

const TITLE_LIMIT = 100

/**
 * A one-line title from a prompt: the first line of the person's own words,
 * cut at the first sentence when that is long enough to name the work, and at
 * a word inside 100 characters otherwise. `null` when nothing is left.
 */
export function titleFromPrompt(text: string): string | null {
  const line = promptText(text)
    .split('\n')
    .map((value) => value.replace(/^[#>*\s-]+/, '').trim())
    .find(Boolean)
  if (!line) return null
  const flat = line.split(/\s+/).join(' ')
  let title = flat
  for (const match of flat.matchAll(/[.?!](?=\s|$)/g)) {
    if (match.index >= 12) {
      title = flat.slice(0, match[0] === '.' ? match.index : match.index + 1)
      break
    }
  }
  const chars = Array.from(title)
  if (chars.length <= TITLE_LIMIT) return title
  const clipped = chars.slice(0, TITLE_LIMIT).join('')
  const space = clipped.lastIndexOf(' ')
  const cut = space > TITLE_LIMIT / 2 ? space : clipped.length
  return `${clipped.slice(0, cut).replace(/[,;:\s]+$/, '')}…`
}

/** The last segment of a source project path, or `null` when the history has none. */
export function projectName(cwd: string | null | undefined): string | null {
  return (
    cwd
      ?.split(/[\\/]+/)
      .filter(Boolean)
      .pop() ?? null
  )
}

/** `workers · Oct 25` for a history with no words of its own to title it by. */
export function fallbackTitle(
  cwd: string | null | undefined,
  timestamp: number,
): string {
  const project = projectName(cwd) ?? 'Conversation'
  const date = new Date(timestamp)
  if (Number.isNaN(date.getTime())) return project
  const day = date.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    timeZone: 'UTC',
  })
  return `${project} · ${day}`
}

/** The title to show for a history, whatever the worker that listed it sent. */
export function conversationTitle(conversation: ExternalConversation): string {
  return (
    titleFromPrompt(conversation.title) ??
    fallbackTitle(conversation.cwd, conversation.created_at)
  )
}

/*
 * Notices. Older workers put three things in `warnings` that are not
 * problems with a history: the per-page skipped count, the preview window,
 * and what every import leaves behind. The dialog says those its own quiet
 * way, so they are taken out here and only real problems stay warnings.
 */

const SKIPPED = /^(\d+) empty, unsupported, or unreadable histor/
const NOT_IMPORTED = /^Reasoning, attachments, and subagent activity/
const PREVIEW_WINDOW = /^Preview shows the last \d+ messages/

export function discoveryNotices(discovery: Discovery): {
  skipped: number
  problems: string[]
} {
  let skipped = discovery.skipped ?? 0
  const problems: string[] = []
  for (const warning of discovery.warnings) {
    const match = SKIPPED.exec(warning)
    if (match) skipped = Math.max(skipped, Number(match[1]))
    else problems.push(warning)
  }
  return { skipped, problems }
}

export function previewNotices(preview: ConversationPreview): {
  truncated: boolean
  problems: string[]
} {
  let truncated = preview.truncated === true
  const problems: string[] = []
  for (const warning of preview.warnings) {
    if (PREVIEW_WINDOW.test(warning)) truncated = true
    else if (!NOT_IMPORTED.test(warning)) problems.push(warning)
  }
  return { truncated, problems }
}

export async function discoverConversations(input: {
  source: ConversationSource
  cursor?: string
  query?: string
}) {
  return (await getIiiClient()).trigger<Discovery>(
    'console::conversations::discover',
    input,
  )
}
export async function previewConversation(
  source: ConversationSource,
  id: string,
) {
  return (await getIiiClient()).trigger<ConversationPreview>(
    'console::conversations::preview',
    { source, id },
  )
}
export async function importConversation(
  source: ConversationSource,
  id: string,
) {
  try {
    // The client's own trigger timeout applies: an import runs batch after batch server-side.
    return await (await getIiiClient()).trigger<ImportResult>(
      'console::conversations::import',
      { source, id },
    )
  } catch (error) {
    // A trigger that times out only stops waiting: the import can still finish, and importing
    // again would make a second copy.
    if (
      error instanceof Error &&
      error.message.startsWith('Invocation timeout')
    ) {
      throw new Error(
        'Timed out waiting for the import. It may still be running, so check your conversations before importing it again.',
      )
    }
    throw error
  }
}
