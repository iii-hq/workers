// Generates src/lib/inline-file-icons.generated.ts: the language marks a
// chat reply shows beside an inline-code file name (`style.css`,
// `Cargo.toml`). It takes a small subset of the IDE worker's Material icon
// set (ide/ui/src/page/file-icons.generated.ts, itself generated from
// material-icon-theme), so the chat and the IDE tree draw the same marks.
// Run `node scripts/inline-file-icons.mjs` from ade/web after the IDE set
// changes, and commit the output.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = readFileSync(join(here, '../../../ide/ui/src/page/file-icons.generated.ts'), 'utf8')

/** The marks worth showing in prose: languages and the files people name. */
const KEEP = new Set([
  'html', 'css', 'sass', 'less', 'tailwindcss',
  'javascript', 'typescript', 'typescript-def', 'react', 'react_ts', 'vue', 'svelte', 'astro',
  'json', 'yaml', 'toml', 'xml', 'markdown', 'mdx', 'readme', 'license', 'log',
  'rust', 'python', 'go', 'java', 'kotlin', 'swift', 'c', 'cpp', 'h', 'hpp', 'csharp', 'ruby', 'php', 'dart', 'lua', 'zig', 'elixir', 'scala',
  'console', 'powershell', 'makefile', 'docker', 'git', 'settings', 'lock', 'key', 'certificate',
  'nodejs', 'npm', 'pnpm', 'yarn', 'bun', 'deno', 'tsconfig', 'vite', 'eslint', 'prettier', 'biome', 'vitest', 'playwright',
  'image', 'svg', 'audio', 'video', 'font', 'pdf', 'zip', 'csv', 'database', 'graphql', 'prisma', 'terraform', 'wasm', 'diff',
])

function readConst(name) {
  const match = new RegExp(`export const ${name}[^=]*= ([^\\n]+)`).exec(source)
  if (!match) throw new Error(`${name} not found in the IDE icon set`)
  return match[1].replace(/;$/, '')
}

const sprite = JSON.parse(readConst('FILE_ICON_SPRITE'))
const byName = JSON.parse(readConst('FILE_ICON_BY_NAME'))
const byExt = JSON.parse(readConst('FILE_ICON_BY_EXT'))

/** id → { viewBox, body } for every kept symbol in the sprite. */
const icons = {}
for (const [, id, viewBox, body] of sprite.matchAll(/<symbol id="mi-([^"]+)" viewBox="([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) {
  if (!KEEP.has(id)) continue
  // A symbol's own presentation attributes (the log mark's stroke) ride on a
  // wrapping group, so the body renders the same outside the sprite.
  const attrs = /<symbol id="mi-[^"]+" viewBox="[^"]+"([^>]*)>/.exec(sprite.slice(sprite.indexOf(`id="mi-${id}"`) - 8))?.[1]?.trim()
  icons[id] = { viewBox, body: attrs ? `<g ${attrs}>${body}</g>` : body }
}
const kept = (table) =>
  Object.fromEntries(
    Object.entries(table)
      .filter(([, id]) => icons[id])
      .map(([key, id]) => [key.toLowerCase(), id]),
  )

const out = `/* Generated by scripts/inline-file-icons.mjs from the IDE's Material icon set; do not edit. */

/** Material file marks by icon id: the SVG viewBox and inner markup. */
export const INLINE_FILE_ICONS: Readonly<Record<string, { viewBox: string; body: string }>> = ${JSON.stringify(icons)}

/** Exact file names (lower-cased) → icon id. */
export const INLINE_FILE_ICON_BY_NAME: Readonly<Record<string, string>> = ${JSON.stringify(kept(byName))}

/** Extensions (lower-cased, no dot, longest compound first when matching) → icon id. */
export const INLINE_FILE_ICON_BY_EXT: Readonly<Record<string, string>> = ${JSON.stringify(kept(byExt))}
`
writeFileSync(join(here, '../src/lib/inline-file-icons.generated.ts'), out)
console.log(`inline file icons: ${Object.keys(icons).length} marks, ${(out.length / 1024).toFixed(1)} KB`)
