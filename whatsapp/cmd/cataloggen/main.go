// Command cataloggen emits SDK schema adapters from the worker API contracts.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strings"
)

func main() {
	b, err := os.ReadFile("catalog.json")
	if err != nil {
		panic(err)
	}
	var entries []struct {
		ID string `json:"id"`
	}
	if err = json.Unmarshal(b, &entries); err != nil {
		panic(err)
	}
	var out strings.Builder
	out.WriteString("// Code generated by go run ./cmd/cataloggen; DO NOT EDIT.\npackage main\nimport iii \"github.com/iii-hq/iii/sdk/packages/go/iii\"\n")
	for i, e := range entries {
		fmt.Fprintf(&out, "type operation%d struct{}\nfunc(operation%d)ID()string{return %q}\n", i, i, e.ID)
	}
	out.WriteString("var typedInstallers=map[string]func(*iii.Client,*Registry)error{\n")
	for i, e := range entries {
		fmt.Fprintf(&out, "%q:installOperation[operation%d],\n", e.ID, i)
	}
	out.WriteString("}\n")
	b, err = format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("catalog_generated.go", b, 0644); err != nil {
		panic(err)
	}
}
