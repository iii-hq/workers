// Generates src/page/file-icons.generated.ts from material-icon-theme: a
// sprite of <symbol>s for the icons the IDE shows (the real HTML, CSS,
// TypeScript, YAML, Rust … marks, as VS Code draws them) and the file-name
// and extension tables that pick them. Only the icons in KEEP are bundled,
// so the sprite stays small; everything else falls back to @pierre/trees'
// built-in set. Run `node scripts/file-icons.mjs` after changing KEEP or
// bumping the package, and commit the output.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const pkg = dirname(require.resolve('material-icon-theme/package.json'))
const manifest = JSON.parse(readFileSync(join(pkg, 'dist/material-icons.json'), 'utf8'))

/** Icon ids worth bundling: languages, configs and assets a worker tree holds. */
const KEEP = new Set([
  'html', 'css', 'sass', 'less', 'postcss', 'tailwindcss',
  'javascript', 'typescript', 'typescript-def', 'react', 'react_ts', 'vue', 'svelte', 'astro', 'next', 'nuxt', 'angular',
  'json', 'yaml', 'toml', 'xml', 'markdown', 'mdx', 'readme', 'changelog', 'contributing', 'license', 'document', 'log',
  'rust', 'python', 'go', 'java', 'kotlin', 'swift', 'c', 'cpp', 'h', 'hpp', 'csharp', 'ruby', 'php', 'dart', 'lua', 'zig', 'elixir', 'haskell', 'scala', 'r', 'perl',
  'console', 'powershell', 'makefile', 'cmake', 'docker', 'git', 'github-actions-workflow', 'editorconfig', 'tune', 'settings', 'lock', 'key', 'certificate',
  'nodejs', 'npm', 'pnpm', 'yarn', 'bun', 'deno', 'tsconfig', 'vite', 'webpack', 'rollup', 'esbuild', 'babel', 'eslint', 'prettier', 'biome',
  'jest', 'vitest', 'playwright', 'cypress', 'storybook', 'test-ts', 'test-js', 'test-jsx',
  'image', 'svg', 'audio', 'video', 'font', 'pdf', 'zip', 'exe', 'binary', 'hex', 'csv', 'table', 'database', 'graphql', 'prisma', 'terraform', 'nginx', 'wasm',
  'claude', 'skill', 'cargo', 'tex', 'word', 'powerpoint', 'diff', 'robots', 'favicon', 'vercel', 'netlify', 'firebase', 'supabase',
])

/** Marks drawn here instead of taken from the theme. A log is a scroll of
    lines in a quiet blue-grey (the theme's olive sheet read as a stain in
    the tree); stroked like lucide, so it sits with the IDE's other glyphs. */
const OVERRIDES = {
  log: '<symbol id="mi-log" viewBox="0 0 24 24" fill="none" stroke="#8fa3b5" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"><path d="M15 12h-5"/><path d="M15 8h-5"/><path d="M19 17V5a2 2 0 0 0-2-2H4"/><path d="M8 21h12a2 2 0 0 0 2-2v-1a1 1 0 0 0-1-1H11a1 1 0 0 0-1 1v1a2 2 0 1 1-4 0V5a2 2 0 1 0-4 0v2a1 1 0 0 0 1 1h3"/></symbol>',
}

const defs = manifest.iconDefinitions
const symbols = []
const bundled = new Set()
for (const id of [...KEEP].sort()) {
  const def = defs[id]
  if (!def) continue
  const svg = readFileSync(join(pkg, 'icons', `${id}.svg`), 'utf8')
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 32 32'
  if (OVERRIDES[id]) {
    symbols.push(OVERRIDES[id])
    bundled.add(id)
    continue
  }
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    // Material's bounding-box path, unfilled in the theme's own SVG root but
    // painted as a solid square once it sits in a symbol.
    .replace(/<path d="M0 0h24v24H0z"\/>/g, '')
    .trim()
  symbols.push(`<symbol id="mi-${id}" viewBox="${viewBox}">${body}</symbol>`)
  bundled.add(id)
}

const byName = {}
for (const [name, id] of Object.entries(manifest.fileNames)) if (bundled.has(id)) byName[name] = id
const byExt = {}
for (const [ext, id] of Object.entries(manifest.fileExtensions)) if (bundled.has(id)) byExt[ext] = id

const out = `/* Generated by scripts/file-icons.mjs from material-icon-theme ${require('material-icon-theme/package.json').version}; do not edit. */

/** <symbol id="mi-<icon>"> definitions, one per bundled icon. */
export const FILE_ICON_SPRITE = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join('')}</svg>`)}

/** Lower-cased file name → icon id. */
export const FILE_ICON_BY_NAME: Readonly<Record<string, string>> = ${JSON.stringify(byName)}

/** Lower-cased extension (no dot; longest wins, e.g. "test.ts" before "ts") → icon id. */
export const FILE_ICON_BY_EXT: Readonly<Record<string, string>> = ${JSON.stringify(byExt)}

export const FILE_ICON_IDS: ReadonlySet<string> = new Set(${JSON.stringify([...bundled])})
`
const target = join(here, '../src/page/file-icons.generated.ts')
writeFileSync(target, out)
console.log(`${bundled.size} icons, ${Object.keys(byName).length} names, ${Object.keys(byExt).length} extensions → ${target} (${(out.length / 1024).toFixed(0)} KB)`)
const missing = [...KEEP].filter((id) => !bundled.has(id))
if (missing.length) console.log('not in the theme:', missing.join(' '))
